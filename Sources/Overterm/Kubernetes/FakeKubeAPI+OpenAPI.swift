/// The fake's `/openapi/v3` (3.15): an index naming a document for each
/// group version it serves, and those documents in the server's shape —
/// component schemas joined by `allOf: [{$ref}]`, each kind's marked with
/// `x-kubernetes-group-version-kind`, every document carrying the shared
/// types it refers to. The built-in kinds the scenarios edit (Deployment,
/// Pod, Service, ConfigMap, Secret) have their real fields, trimmed; the
/// others a `spec` that takes anything; a CRD the schema it was added with.
extension FakeKubeAPI {
    private static let prefix = "#/components/schemas/"
    private static let meta = "io.k8s.apimachinery.pkg.apis.meta.v1."

    /// `allOf: [{$ref}]` as the server writes a field of a named type; `bare`: no `default: {}` beside it.
    private static func ref(_ name: String, _ description: String? = nil, bare: Bool = false) -> [String: Any] {
        var schema: [String: Any] = ["allOf": [["$ref": prefix + name]]]
        if let description { schema["description"] = description }
        if !bare { schema["default"] = [String: Any]() }
        return schema
    }

    private static func string(_ description: String, enum values: [String] = []) -> [String: Any] {
        var schema: [String: Any] = ["type": "string", "description": description, "default": ""]
        if !values.isEmpty { schema["enum"] = values }
        return schema
    }

    private static func integer(_ description: String) -> [String: Any] { ["type": "integer", "format": "int32", "description": description] }

    private static func map(_ description: String, of value: [String: Any] = ["type": "string", "default": ""]) -> [String: Any] {
        ["type": "object", "description": description, "additionalProperties": value]
    }

    private static func array(_ description: String, of item: [String: Any]) -> [String: Any] {
        ["type": "array", "description": description, "items": item]
    }

    private static func object(_ description: String, _ properties: [String: Any], required: [String] = []) -> [String: Any] {
        var schema: [String: Any] = ["type": "object", "description": description, "properties": properties]
        if !required.isEmpty { schema["required"] = required }
        return schema
    }

    private static var apiVersionField: [String: Any] {
        string(
            "APIVersion defines the versioned schema of this representation of an object. Servers should convert recognized schemas to the latest internal value, and may reject unrecognized values.")
    }
    private static var kindField: [String: Any] {
        string(
            "Kind is a string value representing the REST resource this object represents. Servers may infer this from the endpoint the client submits requests to. Cannot be updated. In CamelCase.")
    }

    /// The kind's own schema: apiVersion, kind, metadata and its fields.
    private static func kindSchema(_ description: String, _ properties: [String: Any], gvk: (String, String, String)?) -> [String: Any] {
        var all = properties
        all["apiVersion"] = apiVersionField
        all["kind"] = kindField
        all["metadata"] = ref(meta + "ObjectMeta", "Standard object's metadata.")
        var schema = object(description, all)
        if let gvk { schema["x-kubernetes-group-version-kind"] = [["group": gvk.0, "version": gvk.1, "kind": gvk.2]] }
        return schema
    }

