    /// `com.example.stable.v1.CronTab`: a CRD's schema's name, as the server makes it.
    static func openAPISchemaName(_ kind: Kind) -> String {
        if kind.group.isEmpty { return "io.k8s.api.core.\(kind.version).\(kind.kind)" }
        let builtin = ["apps", "batch", "policy", "autoscaling"]
        if builtin.contains(kind.group) { return "io.k8s.api.\(kind.group).\(kind.version).\(kind.kind)" }
        if kind.group.hasSuffix(".k8s.io") {
            return "io.k8s.api.\(kind.group.dropLast(".k8s.io".count).replacingOccurrences(of: ".", with: "")).\(kind.version).\(kind.kind)"
        }
        return kind.group.split(separator: ".").reversed().joined(separator: ".") + ".\(kind.version).\(kind.kind)"
    }

    /// The index: every group version served, its document's URL and hash.
    static func openAPIIndex(_ kinds: [Kind], crdSchemas: [String: [String: Any]]) -> Data {
        var paths: [String: Any] = [:]
        for groupVersion in Set(kinds.map(\.groupVersion)) {
            let key = groupVersion.contains("/") ? "apis/\(groupVersion)" : "api/\(groupVersion)"
            let hash = openAPIHash(groupVersion, kinds: kinds, crdSchemas: crdSchemas)
            paths[key] = ["serverRelativeURL": "/openapi/v3/\(key)?hash=\(hash)"]
        }
        paths["api"] = ["serverRelativeURL": "/openapi/v3/api?hash=0"]
        paths["apis"] = ["serverRelativeURL": "/openapi/v3/apis?hash=0"]
        return encode(["paths": paths])
    }

    /// FNV-1a of what the document holds: another CRD schema, another hash.
    static func openAPIHash(_ groupVersion: String, kinds: [Kind], crdSchemas: [String: [String: Any]]) -> String {
        let own = kinds.filter { $0.groupVersion == groupVersion }.sorted { $0.kind < $1.kind }
        var text = own.map { $0.kind + "|" + $0.fullName }.joined(separator: ",")
        for kind in own { if let schema = crdSchemas[kind.fullName] { text += String(decoding: encode(schema), as: UTF8.self) } }
        var hash: UInt64 = 0xcbf2_9ce4_8422_2325
        for byte in text.utf8 {
            hash ^= UInt64(byte)
            hash = hash &* 0x100_0000_01b3
        }
        return String(hash, radix: 16, uppercase: true)
    }

    /// `api/v1`, `apis/apps/v1`'s document; nil when nothing is served there.
    static func openAPIDocument(_ key: String, kinds: [Kind], crdSchemas: [String: [String: Any]]) -> Data? {
        let parts = key.split(separator: "/").map(String.init)
        let groupVersion: String
        if parts.count == 2, parts[0] == "api" {
            groupVersion = parts[1]
        } else if parts.count == 3, parts[0] == "apis" {
            groupVersion = parts[1] + "/" + parts[2]
        } else {
            return nil
        }
        let own = kinds.filter { $0.groupVersion == groupVersion }
        guard !own.isEmpty else { return nil }
        var schemas = shared
        for kind in own {
            let gvk = (kind.group, kind.version, kind.kind)
            if let known = kindFields["\(groupVersion)|\(kind.kind)"] {
                schemas[openAPISchemaName(kind)] = kindSchema(known.description, known.properties, gvk: gvk)
                schemas.merge(known.extra) { $1 }
            } else {
                var spec: [String: Any] = [
                    "type": "object", "description": "\(kind.kind)'s desired state.", "x-kubernetes-preserve-unknown-fields": true,
                ]
                if let custom = crdSchemas[kind.fullName] { spec = custom }
                let description = kind.custom ? "\(kind.kind) is a custom resource (\(kind.fullName))." : "\(kind.kind), as this fake API server serves it."
                schemas[openAPISchemaName(kind)] = kindSchema(
                    description,
                    ["spec": spec, "status": ["type": "object", "x-kubernetes-preserve-unknown-fields": true]], gvk: gvk)
            }
        }
        return encode([
            "openapi": "3.0.0", "info": ["title": "Kubernetes", "version": "v1.fake"], "paths": [String: Any](),
            "components": ["schemas": schemas],
        ])
    }
